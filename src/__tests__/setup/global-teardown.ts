// Vitest globalSetup: write src/build-info.ts if it is missing (below), and remove the
// throwaway HOMEs that isolate-home.ts creates under <tmp>/origin-cli-test-runs/<runId>/. Only ever THIS run's directory —
// another suite may be running from another worktree at the same moment, and
// its homes live next to ours. Residue from crashed runs (owning vitest pid no
// longer alive) is swept up front.
import { execFileSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { RUN_ID_ENV, runHomeRoot, sweepDeadRuns } from './test-home.js';

const PKG_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');

// src/build-info.ts is generated by `prepare`, which never ran in a worktree
// whose node_modules was cloned rather than installed. Anything importing
// index.ts needs it, so write it once before the run if it's missing.
function ensureBuildInfo(): void {
  if (fs.existsSync(path.join(PKG_ROOT, 'src', 'build-info.ts'))) return;
  execFileSync(process.execPath, [path.join(PKG_ROOT, 'scripts', 'write-build-info.cjs')], { cwd: PKG_ROOT, stdio: 'ignore' });
}

export default function () {
  ensureBuildInfo();
  sweepDeadRuns();
  const runId = process.env[RUN_ID_ENV];
  if (!runId) return;
  const root = runHomeRoot(runId);
  return () => {
    // ORIGIN_KEEP_TEST_HOMES=1 leaves them behind to read each worker's hooks.log.
    if (process.env.ORIGIN_KEEP_TEST_HOMES === '1') return;
    try { fs.rmSync(root, { recursive: true, force: true }); } catch { /* ignore */ }
  };
}
